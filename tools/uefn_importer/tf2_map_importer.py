"""
tf2_map_importer.py — UEFN Toolbelt Custom Plugin
=================================================

Custom Toolbelt plugin that imports a TF2 map manifest exported by SourceIO into UEFN.
Features:
- Reads map_manifest.json generated by SourceIO UEFN Exporter.
- Imports static meshes (FBX) and textures (PNG/TGA) into /Game/TF2_Map/ via AssetTools.
- Spawns StaticMeshActors and Device placeholders in batches with correct transforms.
- Full idempotency: safe to re-run, updates existing actors or cleans them up on demand.
- Outliner organization: sorts actors into clean folder hierarchies (TF2_Map/Props, TF2_Map/World, etc.).
- Exposes tools via @register_tool for Toolbelt UI and MCP remote execution.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any, Optional

try:
    import unreal
    IN_UNREAL = True
except ImportError:
    unreal = None
    IN_UNREAL = False

try:
    from UEFN_Toolbelt.registry import register_tool
except ImportError:
    # Fallback decorator if loaded standalone
    def register_tool(*args, **kwargs):
        def decorator(f):
            return f
        return decorator


TAG_TF2_IMPORTED = "TF2_Imported"
DEFAULT_DEST_PATH = "/Game/TF2_Map"


@register_tool(
    name="tf2_import_manifest",
    category="TF2",
    description="Import a complete TF2 map from map_manifest.json into UEFN with batching and idempotency.",
    tags=["tf2", "import", "bsp", "manifest", "actors", "mcp"],
)
def run_import_manifest(
    manifest_path: str = "",
    import_assets: bool = True,
    spawn_actors: bool = True,
    batch_size: int = 250,
    clean_existing: bool = True,
    **kwargs,
) -> dict[str, Any]:
    """
    Main entry point for importing a TF2 map into UEFN.

    Args:
        manifest_path: Absolute path to map_manifest.json. If empty, checks Saved/UEFN_Export/map_manifest.json.
        import_assets: Whether to import FBX meshes and textures into Content Browser.
        spawn_actors: Whether to spawn actors into the active editor level.
        batch_size: Actor spawning batch size to prevent Slate UI hitching.
        clean_existing: If True, deletes previous TF2_Imported actors before spawning.
    """
    if not IN_UNREAL:
        return {"status": "error", "error": "This tool must be run inside UEFN with Python enabled."}

    manifest_file = _resolve_manifest_path(manifest_path)
    if not manifest_file.exists():
        return {
            "status": "error",
            "error": f"Manifest file not found: {manifest_file}. Please run the SourceIO UEFN Exporter first.",
        }

    try:
        with open(manifest_file, "r", encoding="utf-8") as f:
            manifest_data = json.load(f)
    except Exception as e:
        return {"status": "error", "error": f"Failed reading manifest JSON: {e}"}

    manifest_dir = manifest_file.parent
    map_name = manifest_data.get("map_name", "TF2_Map")
    actors_data = manifest_data.get("actors", [])

    results = {
        "status": "ok",
        "map_name": map_name,
        "manifest_path": str(manifest_file),
        "total_manifest_actors": len(actors_data),
        "assets_imported": 0,
        "actors_spawned": 0,
        "actors_cleaned": 0,
        "failures": [],
    }

    # 1. Clean existing imported actors if requested
    if clean_existing:
        clean_res = run_clean_imported()
        results["actors_cleaned"] = clean_res.get("deleted_count", 0)

    # 2. Import Assets (FBX Meshes & Textures)
    if import_assets:
        asset_res = _import_assets(manifest_dir, manifest_data)
        results["assets_imported"] = asset_res.get("imported_count", 0)
        results["failures"].extend(asset_res.get("failures", []))

    # 3. Spawn Actors in Level
    if spawn_actors:
        spawn_res = _spawn_actors_in_batches(actors_data, batch_size)
        results["actors_spawned"] = spawn_res.get("spawned_count", 0)
        results["failures"].extend(spawn_res.get("failures", []))

    # 4. Write Import Audit Report
    _write_import_report(manifest_dir, results)

    return results


@register_tool(
    name="tf2_clean_imported",
    category="TF2",
    description="Safely removes all TF2 actors tagged with 'TF2_Imported' from the current level.",
    tags=["tf2", "clean", "undo", "delete", "safe"],
)
def run_clean_imported(**kwargs) -> dict[str, Any]:
    """
    Deletes all actors tagged with TAG_TF2_IMPORTED for clean undo.
    """
    if not IN_UNREAL:
        return {"status": "error", "error": "This tool must be run inside UEFN."}

    actor_sub = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
    all_actors = actor_sub.get_all_level_actors()

    deleted = 0
    with unreal.ScopedEditorTransaction("TF2 Clean Imported Actors") as _:
        for actor in all_actors:
            if not actor:
                continue
            actor_tags = [str(t) for t in actor.tags]
            if TAG_TF2_IMPORTED in actor_tags or str(actor.get_folder_path()).startswith("TF2_Map"):
                actor_sub.destroy_actor(actor)
                deleted += 1

    return {"status": "ok", "deleted_count": deleted}


@register_tool(
    name="tf2_spawn_actors_only",
    category="TF2",
    description="Spawns actors from map_manifest.json assuming FBX assets are already imported in Content Browser.",
    tags=["tf2", "spawn", "actors", "batch"],
)
def run_spawn_actors_only(
    manifest_path: str = "",
    batch_size: int = 250,
    **kwargs,
) -> dict[str, Any]:
    manifest_file = _resolve_manifest_path(manifest_path)
    if not manifest_file.exists():
        return {"status": "error", "error": f"Manifest not found: {manifest_file}"}

    with open(manifest_file, "r", encoding="utf-8") as f:
        data = json.load(f)

    actors = data.get("actors", [])
    res = _spawn_actors_in_batches(actors, batch_size)
    return {"status": "ok", "spawned_count": res.get("spawned_count", 0), "failures": res.get("failures", [])}


