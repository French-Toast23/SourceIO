def _resolve_manifest_path(user_path: str) -> Path:
    if user_path and user_path.strip():
        return Path(user_path.strip())

    proj_dir = Path(unreal.Paths.project_dir()) if IN_UNREAL else Path.cwd()
    # Check default locations
    candidates = [
        proj_dir / "Saved" / "UEFN_Export" / "map_manifest.json",
        proj_dir / "Content" / "TF2_Export" / "map_manifest.json",
        proj_dir / "docs" / "map_manifest.json",
        Path("C:/Users/anxoj/Documents/Fortnite Projects/TwoFortDef/Saved/UEFN_Export/map_manifest.json"),
    ]
    for c in candidates:
        if c.exists():
            return c
    return candidates[0]


def _import_assets(manifest_dir: Path, manifest_data: dict[str, Any]) -> dict[str, Any]:
    """
    Imports FBX meshes and texture files into /Game/TF2_Map/.
    """
    asset_tools = unreal.AssetToolsHelpers.get_asset_tools()
    tasks: list[unreal.AssetImportTask] = []
    failures = []

    meshes_dir = manifest_dir / "Meshes"
    textures_dir = manifest_dir / "Textures"

    # 1. Collect FBX Meshes
    if meshes_dir.exists():
        for fbx in meshes_dir.glob("*.fbx"):
            task = unreal.AssetImportTask()
            task.filename = str(fbx)
            task.destination_path = f"{DEFAULT_DEST_PATH}/Meshes"
            task.destination_name = fbx.stem
            task.replace_existing = True
            task.automated = True
            task.save = True

            # Static Mesh FBX options
            fbx_options = unreal.FbxImportUI()
            fbx_options.import_mesh = True
            fbx_options.import_textures = False
            fbx_options.import_materials = False
            fbx_options.import_as_skeletal = False
            fbx_options.static_mesh_import_data.combine_meshes = True
            fbx_options.static_mesh_import_data.auto_generate_collision = False  # Use our UCX_ collision
            task.options = fbx_options
            tasks.append(task)

    # 2. Collect Textures
    if textures_dir.exists():
        for tex_file in list(textures_dir.glob("*.png")) + list(textures_dir.glob("*.tga")):
            task = unreal.AssetImportTask()
            task.filename = str(tex_file)
            task.destination_path = f"{DEFAULT_DEST_PATH}/Textures"
            task.destination_name = tex_file.stem
            task.replace_existing = True
            task.automated = True
            task.save = True
            tasks.append(task)

    if tasks:
        try:
            asset_tools.import_asset_tasks(tasks)
        except Exception as e:
            failures.append(f"Import task error: {e}")

    imported_count = sum(1 for t in tasks if t.imported_object is not None)
    return {"imported_count": imported_count, "failures": failures}


def _spawn_actors_in_batches(actors_data: list[dict[str, Any]], batch_size: int) -> dict[str, Any]:
    """
    Spawns actors into the active editor world using ScopedEditorTransaction and batching.
    """
    actor_sub = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
    spawned_count = 0
    failures = []

    mesh_cache: dict[str, unreal.StaticMesh] = {}

    with unreal.ScopedEditorTransaction("TF2 Spawn Map Actors") as _:
        for i, a_data in enumerate(actors_data):
            actor_name = a_data.get("actor_name", f"TF2_Actor_{i}")
            asset_ref = a_data.get("asset_reference")
            loc_list = a_data.get("location", [0.0, 0.0, 0.0])
            rot_list = a_data.get("rotation", [0.0, 0.0, 0.0])
            scale_list = a_data.get("scale", [1.0, 1.0, 1.0])
            ent_class = a_data.get("entity_class", "prop_static")
            is_gameplay = a_data.get("is_gameplay_entity", False)

            loc = unreal.Vector(loc_list[0], loc_list[1], loc_list[2])
            rot = unreal.Rotator(rot_list[0], rot_list[1], rot_list[2])  # Pitch, Yaw, Roll
            scale = unreal.Vector(scale_list[0], scale_list[1], scale_list[2])

            mesh_obj = None
            if asset_ref:
                mesh_stem = Path(asset_ref).stem
                if mesh_stem not in mesh_cache:
                    mesh_asset_path = f"{DEFAULT_DEST_PATH}/Meshes/{mesh_stem}"
                    mesh_obj = unreal.load_asset(mesh_asset_path)
                    mesh_cache[mesh_stem] = mesh_obj
                else:
                    mesh_obj = mesh_cache[mesh_stem]

            try:
                # Spawn actor
                actor = unreal.EditorLevelLibrary.spawn_actor_from_class(unreal.StaticMeshActor, loc, rot)
                if not actor:
                    failures.append(f"Could not spawn actor {actor_name}")
                    continue

                actor.set_actor_label(actor_name)
                actor.set_actor_scale3d(scale)

                # Set Static Mesh if available
                if mesh_obj and hasattr(actor, "static_mesh_component"):
                    actor.static_mesh_component.set_static_mesh(mesh_obj)

                # Tag for tracking and idempotency
                actor.tags.append(unreal.Name(TAG_TF2_IMPORTED))

                # Set Outliner folder
                folder = "TF2_Map/Props"
                if "chunk" in actor_name.lower() or "world" in actor_name.lower():
                    folder = "TF2_Map/World"
                elif is_gameplay:
                    folder = "TF2_Map/Logic"
                elif "audio" in actor_name.lower():
                    folder = "TF2_Map/Audio"

                actor.set_folder_path(unreal.Name(folder))
                spawned_count += 1
            except Exception as e:
                failures.append(f"Exception spawning {actor_name}: {e}")

    return {"spawned_count": spawned_count, "failures": failures}


def _write_import_report(output_dir: Path, results: dict[str, Any]) -> None:
    report_file = output_dir / "import_report.json"
    try:
        with open(report_file, "w", encoding="utf-8") as f:
            json.dump(results, f, indent=2)
    except Exception as e:
        print(f"Warning: could not write import_report.json: {e}")
